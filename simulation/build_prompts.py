"""Generate supabase/functions/_shared/prompts.generated.ts from the prompt files.

    python simulation/build_prompts.py            # write the file
    python simulation/build_prompts.py --check    # fail if the generated file is out of date

The caller-turn Edge Function bundles these strings instead of reading files at run time. Edit the
files in simulation/prompts/, run this, and deploy. Never edit the generated file by hand.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import callers  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "supabase" / "functions" / "_shared" / "prompts.generated.ts"


def render() -> str:
    def lit(text: str) -> str:
        return json.dumps(text, ensure_ascii=False)

    styles = ",\n".join(f"  {lang}: {lit(text)}" for lang, text in callers.load_styles().items())
    moods = ",\n".join(f"  {lit(name)}: {lit(text)}" for name, text in callers.load_moods().items())
    return (
        "// GENERATED by simulation/build_prompts.py from simulation/prompts/*. Do not edit by hand.\n\n"
        f"export const BASE_PROMPT = {lit(callers.load_base())};\n\n"
        f"export const LANGUAGE_STYLES: Record<string, string> = {{\n{styles},\n}};\n\n"
        f"export const MOODS: Record<string, string> = {{\n{moods},\n}};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is out of date. Run: python simulation/build_prompts.py")
            return 1
        print(f"{OUT.name} is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} ({len(text):,} characters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
